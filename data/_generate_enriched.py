# status → updated_at offset hours (relative to created_at)
_STATUS_UPDATE_HOURS = {
    "DETECTED":     4,
    "INVESTIGATING": 12,
    "CONTAINED":    36,
    "MITIGATED":    72,
    "RESOLVED":     120,
}

# ---------------------------------------------------------------------------
# Load existing sparse incidents and enrich
# ---------------------------------------------------------------------------

def enrich_incidents() -> list[dict]:
    src = json.loads((ROOT / "sample_incidents.json").read_text(encoding="utf-8"))
    enriched = []
    for inc in src:
        iid = inc["incident_id"]
        meta = ENRICHMENTS.get(iid, {})
        status = meta.get("status", "INVESTIGATING")

        # Parse created_at to compute updated_at
        created_raw = inc.get("created_at", "2026-05-18T00:00:00Z")
        # Simple offset: add hours based on status
        from datetime import datetime, timedelta, timezone
        try:
            created = datetime.fromisoformat(created_raw.replace("Z", "+00:00"))
        except ValueError:
            created = datetime(2026, 5, 18, tzinfo=timezone.utc)
        offset_h = _STATUS_UPDATE_HOURS.get(status, 24)
        updated = created + timedelta(hours=offset_h)

        out = {
            "incident_id": inc["incident_id"],
            "threat_name": inc["threat_name"],
            "severity": inc["severity"],
            "status": status,
            "campaign_id": inc["campaign_id"],
            "created_at": created_raw,
            "updated_at": updated.strftime("%Y-%m-%dT%H:%M:%SZ"),
            "indicators": inc.get("indicators", []),
            "confidence_score": meta.get("confidence_score", 0.70),
            "risk_score": meta.get("risk_score", 0.60),
            "attribution_confidence": meta.get("attribution_confidence", 0.60),
            "suspected_actor": meta.get("suspected_actor", "UNKNOWN"),
            "attack_techniques": meta.get("attack_techniques", []),
            "description": meta.get("description", ""),
            "assigned_analyst": meta.get("assigned_analyst", "Tom Brandt"),
            "ioc_enrichments": meta.get("ioc_enrichments", ""),
            "mitigation_actions": meta.get("mitigation_actions", ""),
            "threat_summary": meta.get("threat_summary", ""),
            "enrichment_data": meta.get("enrichment_data", {}),
        }
        enriched.append(out)
    return enriched


if __name__ == "__main__":
    incidents = enrich_incidents()
    out_incidents = ROOT / "sample_incidents.json"
